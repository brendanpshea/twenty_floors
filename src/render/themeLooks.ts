import type { ThemeId } from '../core/types';

/** Everything that makes a theme look like itself. Colours are 0xRRGGBB. */
/**
 * Floor detail (the crypt pilot, 28 November 2026; other themes to follow): flagstone slabs, cracks placed where damage
 * makes sense (near walls and heavy props) with a chipped rim, grime along the foot of walls, soft contact shadows under
 * props, and small clutter scattered off the tile centre. Colours are hex; see floorBuilder.ts.
 */
export interface FloorDetail {
  /** Split tiles into 1 to 3 slabs with joints. */
  slabs: boolean;
  /** Crack core and the lighter chipped rim beside it. */
  crack: number;
  rim: number;
  /** Multiplier at the foot of a wall (white = none), fading out `grimeDepth` world units in (a cell is 2). */
  grime: number;
  grimeDepth: number;
  /** Multiplier at the centre of a prop's contact shadow. */
  shadow: number;
  /** If set, crack cores glow in this colour (drawn unlit: magma in hell, heat in the foundry). */
  glow?: number;
  /** If set, slab joints take this colour (moss in the sewers, frost in ice) instead of plain shadow. */
  joint?: number;
  /** Multiplies how many tiles crack (default 1). */
  crackRate?: number;
  /** 'organic': random-walk cracks of varied size with forks and a jagged rim (pilot). Default: the simple crack. */
  crackStyle?: 'organic';
}

export interface ThemeLook {
  id: ThemeId;
  /** Richer floor detail (see FloorDetail). Absent: the plain floor of before. */
  detail?: FloorDetail;
  wallStyle: 'rough' | 'dressed' | 'jagged' | 'foliage';
  /**
   * Required with wallStyle 'foliage': Wall cells that border open ground are drawn as a dense wall of
   * vegetation, `hMin`..`hMax` units tall (varying cell to cell), with `trunk`-coloured shadowed lower
   * sides and a lumpy canopy in the three `greens`. Also softens the floor (no tile cracks, smooth patches).
   */
  foliage?: { hMin: number; hMax: number; trunk: number; greens: [number, number, number]; /** Scales the canopy's lumpiness (1 = rounded foliage, ~2 = spiky reeds). */ lumpy?: number };
  /**
   * If set, the chasm is open air (a long drop into haze): cliff faces fade to `chasmGlow` instead of black
   * and the haze below is drawn as a soft bright cloud floor.
   */
  sky?: boolean;
  /** Outdoor themes: the backdrop is a vertical gradient from `fog` at the horizon (screen bottom) to this at the top. */
  skyTop?: number;
  /** Colour set for move/target/area/danger highlights so they read on this theme's floor. Default blue/red/orange. */
  highlight?: 'default' | 'warm' | 'cool' | 'green';
  floorA: number;
  floorB: number;
  /** Colour of the bevel groove between tiles, as a multiplier. */
  groove: number;
  wall: number;
  wall2: number;
  cap: number;
  water: number;
  waterBed: number;
  waterOpacity: number;
  /**
   * If set, water cells are drawn as a frozen sheet instead of liquid: an opaque, unanimated
   * slab of `color` ice with patches and cracks of `deep` (the dark water showing through).
   */
  ice?: { color: number; deep: number };
  /** Fog and clear colour. */
  fog: number;
  fogDensity: number;
  hemiSky: number;
  hemiGround: number;
  hemiIntensity: number;
  keyColor: number;
  keyIntensity: number;
  /** Ambient term baked into vertex colours (before lights). */
  baseLight: number;
  /** Multiplier on baked point light contribution. */
  lightGain: number;
  /** Real point light intensity multiplier. */
  pointGain: number;
  /** Strength of the always-on light around the camera target. */
  heroGain: number;
  /** Colour of that light (warm in warrens, neutral-cool elsewhere). */
  heroColor: number;
  /** Chasm glow far below. */
  chasmGlow: number;
  /**
   * If set, the chasm is a river of molten slag: a glowing animated surface `depth` units below
   * the lowest floor (replacing the far-below glow), with `color` as the hot slag and `crust` the cooled patches.
   */
  lava?: { color: number; crust: number; depth: number };
  moteColor: number;
  moteCount: number;
  /** Flame colour pairs for torch/brazier/campfire (outer, core). */
  flame: number;
  flameCore: number;
  /** Alternate warm torch (used on a share of torches in the crypt). */
  flameAlt: number;
  altShare: number;
  crystal: number[];
  mushroom: number;
  prop: {
    stone: number;
    stoneDark: number;
    wood: number;
    woodDark: number;
    iron: number;
    bone: number;
    clay: number;
    /** Foliage greens (gnarled trees, bushes, vines); themes without plants can omit them. */
    leaf?: number;
    leafLight?: number;
  };
}

