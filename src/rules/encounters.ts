/** The level budget for a floor: the theme's own figure at this depth if it has one. */
export function levelBudgetAt(depth: number, theme?: ThemeId): number {
  const scale = ENCOUNTER_TUNING.depthScale[Math.min(Math.max(depth, 1), 20) - 1] ?? 1;
  const own = theme ? ENCOUNTER_TUNING.themeTuning[theme]?.[depth]?.budget : undefined;
  if (own !== undefined) return own * scale;
  const table = ENCOUNTER_TUNING.budgetByLevel;
  return (table[Math.min(Math.max(depth, 1), table.length) - 1] as number) * scale;
}

export function minMonstersAt(depth: number): number {
  const t = ENCOUNTER_TUNING.minMonstersPerRoom;
  return t[Math.min(Math.max(depth, 1), t.length) - 1] as number;
}

export function maxMonstersAt(depth: number): number {
  const t = ENCOUNTER_TUNING.maxMonstersPerRoom;
  return t[Math.min(Math.max(depth, 1), t.length) - 1] as number;
}

export function bossMinionChanceAt(depth: number): number {
  const t = ENCOUNTER_TUNING.bossMinionChance;
  return t[Math.min(Math.max(depth, 1), t.length) - 1] as number;
}

export function bossMinionLimit(depth: number): number {
  const t = ENCOUNTER_TUNING.maxBossMinions;
  return t[Math.min(Math.max(depth, 1), t.length) - 1] as number;
}

export function roomBudget(
  depth: number,
  roomRole: keyof typeof ENCOUNTER_TUNING.roomRoleFactor,
  distanceFromEntrance: number,
  theme?: ThemeId,
): number {
  const t = ENCOUNTER_TUNING;
  const base = levelBudgetAt(depth, theme);
  const dist = Math.min(t.distanceCap, t.distanceBase + t.perDistance * distanceFromEntrance);
  return base * t.soloFactor * t.roomRoleFactor[roomRole] * dist;
}

/** The posts each tactic wants, best first (see SpawnPost). */
const POST_PREFERENCE: Record<MonsterTactic, SpawnPost[]> = {
  archer: ['high', 'back', 'flank', 'escort', 'guard', 'front', 'hidden'],
  caster: ['high', 'back', 'escort', 'flank', 'guard', 'front', 'hidden'],
  brute: ['front', 'guard', 'flank', 'escort', 'back', 'high', 'hidden'],
  guard: ['guard', 'front', 'escort', 'flank', 'back', 'high', 'hidden'],
  skirmisher: ['flank', 'front', 'hidden', 'guard', 'escort', 'back', 'high'],
  lurker: ['hidden', 'flank', 'back', 'guard', 'front', 'escort', 'high'],
  leader: ['back', 'escort', 'high', 'guard', 'flank', 'front', 'hidden'],
};

/** Who picks first: the roles with the narrowest wishes (a lurker needs a hidden spot, a leader a back one). */
const PICK_ORDER: MonsterTactic[] = ['lurker', 'leader', 'archer', 'caster', 'skirmisher', 'guard', 'brute'];

/**
 * Match chosen monsters to spawn slots by tactic and post (archers and casters to high and back ground, brutes and
 * guards to the front, skirmishers to the flanks, lurkers to hidden spots, leaders to the back). Uses no randomness:
 * ties go to the earlier slot of the (already shuffled) list. Without posts on the slots it is the old behaviour:
 * the i-th monster takes the i-th slot. Returns one slot per monster, index-aligned with `defs`.
 */
export function assignSlots(defs: MonsterDef[], slots: SpawnSlot[]): SpawnSlot[] {
  if (!slots.some((s) => s.post !== undefined)) return defs.map((_, i) => slots[i] as SpawnSlot);
  const pool = slots.slice();
  const out = new Array<SpawnSlot>(defs.length);
  const order = defs.map((d, i) => ({ d, i, t: tacticOf(d) })).sort((a, b) => PICK_ORDER.indexOf(a.t) - PICK_ORDER.indexOf(b.t) || a.i - b.i);
  for (const { i, t } of order) {
    const pref = POST_PREFERENCE[t];
    let best = -1;
    let bestRank = Infinity;
    pool.forEach((slot, k) => {
      const rank = slot.post === undefined ? 3 : pref.indexOf(slot.post);
      if (rank < bestRank) {
        bestRank = rank;
        best = k;
      }
    });
    out[i] = pool.splice(best, 1)[0] as SpawnSlot;
  }
  return out;
}

function pickGroup(pool: MonsterDef[], maxCount: number, budget: number, depth: number, rng: Rng): MonsterDef[] {
  const minRaw = minMonstersAt(depth);
  const wantMin = Math.min(Math.floor(minRaw) + (rng.chance(minRaw - Math.floor(minRaw)) ? 1 : 0), maxCount);
  const t = ENCOUNTER_TUNING;
  const chosen: MonsterDef[] = [];
  let remaining = budget;
  let overUsed = 0;
  const minXp = Math.min(...pool.map((m) => m.xp));
  while (chosen.length < maxCount) {
    const cap = chosen.length === 0 ? budget * t.firstOvershoot : remaining * t.overshoot;
    const cands = pool.filter((m) => m.xp <= cap && (m.cr <= depth || overUsed < t.maxOverLevel));
    if (cands.length === 0) break;
    const m = rng.weighted(
      cands,
      cands.map((x) => (x.role === 'boss' ? t.roleWeight.elite : t.roleWeight[x.role]) * (t.monsterWeight[x.id] ?? 1)),
    );
    chosen.push(m);
    remaining -= m.xp;
    if (m.cr > depth) overUsed++;
    if (remaining < minXp * 0.9) break;
  }
  if (chosen.length === 0) {
    const legal = pool.filter((m) => m.cr <= depth);
    const from = legal.length > 0 ? legal : pool;
    chosen.push(from.reduce((a, b) => (b.xp < a.xp ? b : a)));
  }
  // Populate: top up to the minimum group size with the cheapest legal monsters.
  while (chosen.length < wantMin && chosen.reduce((n, m) => n + m.xp, 0) < budget * t.topUpLimit) {
    const overUsedNow = chosen.filter((m) => m.cr > depth).length;
    const cheap = pool.filter((m) => m.cr <= depth || overUsedNow < t.maxOverLevel).sort((x, y) => x.xp - y.xp);
    const lowest = cheap[0]?.xp ?? 0;
    chosen.push(rng.pick(cheap.filter((m) => m.xp === lowest)));
  }
  return chosen;
}

/**
 * Populate a floor. Hero level is assumed to equal plan.depth. Only monsters
 * whose themes include plan.theme are used.
 */
export function buildEncounters(plan: FloorPlan, monsters: MonsterDef[], rng: Rng): PlacedMonster[] {
  const themed = monsters.filter((m) => m.themes.includes(plan.theme));
  if (themed.length === 0) return [];
  const forcedBossId = ENCOUNTER_TUNING.themeTuning[plan.theme]?.[plan.depth]?.boss ?? ENCOUNTER_TUNING.bossByDepth[plan.depth];
  const forcedBoss = forcedBossId ? themed.find((m) => m.id === forcedBossId) : undefined;
  const isBoss = (m: MonsterDef): boolean => (forcedBoss ? m.id === forcedBoss.id : m.role === 'boss');
  const t = ENCOUNTER_TUNING;
  const eliteCr = plan.depth >= t.eliteBossFromDepth && forcedBoss ? Math.min(plan.depth * t.eliteBossCr, forcedBoss.cr - 1) : -1;
  const eligible = themed.filter(
    (m) =>
      !isBoss(m) &&
      (m.role !== 'boss' || m.cr <= eliteCr) &&
      plan.depth >= (ENCOUNTER_TUNING.monsterMinDepth[m.id] ?? 1) &&
      plan.depth <= (ENCOUNTER_TUNING.monsterMaxDepth[m.id] ?? Infinity),
  );
  // Leave out what the floor cannot afford yet, unless the theme has nothing cheaper...
  const levelBudget = levelBudgetAt(plan.depth, plan.theme);
  const affordable = eligible.filter((m) => m.xp <= levelBudget * t.soloFactor * t.castBudgetFactor);
  const cheapest = Math.min(...eligible.map((m) => m.xp));
  const inReach = affordable.length > 0 ? affordable : eligible.filter((m) => m.xp === cheapest);
  // ...and what the floor has outgrown, unless it has nothing stronger.
  const minCr = Math.floor(plan.depth * t.minCrPerDepth);
  const worth = levelBudget * t.soloFactor * t.castFloorFactor;
  const strong = inReach.filter((m) => m.cr >= minCr && m.xp >= worth);
  const fallback = inReach.filter((m) => m.cr >= minCr);
  let regular = strong.length > 0 ? strong : fallback.length > 0 ? fallback : inReach;
  // A big cast is sampled, so two floors of one theme (or two runs) do not field the same monsters.
  if (regular.length > t.maxCastSize) regular = rng.shuffle(regular.slice()).slice(0, t.maxCastSize);
  // Bosses that fit this depth; failing that, the one nearest to fitting.
  let bosses = themed.filter(isBoss);
  if (!forcedBoss && bosses.length > 1) {
    const lo = plan.depth * t.bossCrBand[0];
    const hi = plan.depth * t.bossCrBand[1];
    const miss = (m: MonsterDef): number => (m.cr < lo ? lo - m.cr : m.cr > hi ? m.cr - hi : 0);
    const best = Math.min(...bosses.map(miss));
    bosses = bosses.filter((m) => miss(m) === best);
  }
  const out: PlacedMonster[] = [];

  const roomIds = [...new Set(plan.spawns.map((s) => s.roomId))].sort((a, b) => a - b);
  for (const roomId of roomIds) {
    const room = plan.rooms.find((r) => r.id === roomId);
    if (!room || room.role === 'entrance') continue;
    const monsterSlots = rng.shuffle(plan.spawns.filter((s) => s.roomId === roomId && s.role === 'monster'));
    const bossSlots = plan.spawns.filter((s) => s.roomId === roomId && s.role === 'boss');
    const placements: { def: MonsterDef; slot: SpawnSlot; boss?: boolean }[] = [];

    let bossDef: MonsterDef | undefined;
    if (room.role === 'boss' || bossSlots.length > 0) {
      const fallback = [...themed].sort((a, b) => b.cr - a.cr)[0];
      bossDef = bosses.length > 0 ? rng.pick(bosses) : fallback;
    }
    if (bossDef) {
      const bossSlot = bossSlots[0] ?? monsterSlots.shift();
      if (bossSlot) placements.push({ def: bossDef, slot: bossSlot, boss: true });
      // Boss escorts must fit the boss-room budget, so a 200 XP "standard" monster is never an escort at low depth.
      const escortCap = Math.max(roomBudget(plan.depth, 'boss', room.distanceFromEntrance, plan.theme) * 1.2, Math.min(...regular.map((m) => m.xp)));
      const legal = regular.filter((m) => m.cr <= plan.depth && m.xp <= escortCap);
      const minionPool = legal.filter((m) => m.role === 'minion');
      // From floor 4 the boss room is the peak of the floor: escorts of any role (not only minions), one more than before,
      // up to the boss-room budget (re-tune: with minion-only escorts a rested party burst the boss down and lost a tenth of its HP).
      const rich = plan.depth >= ENCOUNTER_TUNING.richEscortsFromDepth;
      const pool = rich && legal.length > 0 ? legal : minionPool.length > 0 ? minionPool : legal.filter((m) => m.role === 'standard');
      const cap = pool.length > 0 ? Math.min(bossMinionLimit(plan.depth) + (rich ? 1 : 0), monsterSlots.length) : 0;
      let n = 0;
      for (let i = 0; i < cap; i++) if (rng.chance(bossMinionChanceAt(plan.depth))) n++;
      const escorts: MonsterDef[] = [];
      let spent = 0;
      for (let i = 0; i < n; i++) {
        const pick = rng.pick(pool);
        if (rich && escorts.length > 0 && spent + pick.xp > escortCap * 1.6) break;
        spent += pick.xp;
        escorts.push(pick);
      }
      const escortSlots = assignSlots(escorts, monsterSlots);
      escorts.forEach((def, i) => placements.push({ def, slot: escortSlots[i] as SpawnSlot }));
    } else if (monsterSlots.length > 0 && regular.length > 0) {
      const budget = roomBudget(plan.depth, room.role, room.distanceFromEntrance, plan.theme);
      if (budget > 0) {
        const group = pickGroup(regular, Math.min(maxMonstersAt(plan.depth), monsterSlots.length), budget, plan.depth, rng);
        const groupSlots = assignSlots(group, monsterSlots);
        group.forEach((def, i) => placements.push({ def, slot: groupSlots[i] as SpawnSlot }));
      }
    }

    // Names: duplicates within a room get a letter suffix.
    const totals = new Map<string, number>();
    for (const p of placements) totals.set(p.def.id, (totals.get(p.def.id) ?? 0) + 1);
    const seen = new Map<string, number>();
    placements.forEach((p, n) => {
      const creature = instantiateMonster(p.def, `m_${roomId}_${n}`, p.slot.pos);
      // The floor's boss carries the hidden `_boss` flag (the combat engine gives it boss momentum from a set depth).
      if (p.boss) creature.resources['_boss'] = flagPool('boss');
      // A monster with both a good bow and a good sword plays the role its post gives it: archer on a high or back post,
      // the alternative (guard or brute) on a front, guard or flank post. Without a post it keeps its default.
      if (isFlexible(p.def) && p.slot.post !== undefined) {
        const t: MonsterTactic = p.slot.post === 'high' || p.slot.post === 'back' ? 'archer' : p.slot.post === 'front' || p.slot.post === 'guard' || p.slot.post === 'flank' ? flexibleAlternative(p.def) : tacticOf(p.def);
        creature.resources[`_tactic_${t}`] = flagPool(`tactic_${t}`);
      }
      if ((totals.get(p.def.id) ?? 0) > 1) {
        const k = seen.get(p.def.id) ?? 0;
        seen.set(p.def.id, k + 1);
        creature.name = `${p.def.name} ${String.fromCharCode(65 + k)}`;
      }
      out.push({ creature, roomId });
    });
  }
  return out;
}
