import type { Rng } from '../core/rng';
import type { Creature, FloorPlan, MonsterDef, MonsterTactic, SpawnPost, SpawnSlot, ThemeId } from '../core/types';
import { flexibleAlternative, isFlexible, tacticOf } from './tactics';
import { flagPool } from './util';
import { THEME_TUNING, type ThemeTuning } from './encounterTable';
import { instantiateMonster } from './monster';

export interface PlacedMonster {
  creature: Creature;
  roomId: number;
}

export interface EncounterTuning {
  budgetByLevel: number[];
  soloFactor: number;
  roomRoleFactor: { entrance: number; combat: number; treasure: number; passage: number; boss: number };
  perDistance: number;
  distanceBase: number;
  distanceCap: number;
  overshoot: number;
  /** The first monster of a room may cost up to this multiple of the budget. */
  firstOvershoot: number;
  maxMonstersPerRoom: number[];
  maxOverLevel: number;
  /** Boss room: at most this many extra monsters, by depth (index depth-1, last value repeats). */
  maxBossMinions: number[];
  /** Ordinary combat rooms get at least this many monsters when there are enough slots (by depth, last value repeats); a fraction is the chance of one more, e.g. 1.6 = 60% of rooms get two. */
  minMonstersPerRoom: number[];
  /** A group is not topped up to the minimum size once its XP already exceeds the budget by this factor (keeps one big monster alone). */
  topUpLimit: number;
  /** Chance that each possible boss escort actually appears, by depth (same indexing). */
  bossMinionChance: number[];
  roleWeight: { minion: number; standard: number; elite: number; boss: number };
  /** Extra selection weight multiplier per monster id (default 1). */
  monsterWeight: Record<string, number>;
  /**
   * The hero gains a level per floor, so a monster far below the floor's level is not a threat
   * worth a turn: ordinary monsters need a CR of at least floor(depth x this). 0.25 lets a
   * CR 1 monster appear up to floor 7 and a CR 2 monster up to floor 11. If no monster of the
   * theme is that strong, the rule is waived for the floor rather than leaving rooms empty.
   */
  minCrPerDepth: number;
  /**
   * A floor's boss is a boss-role monster of the theme with a CR between depth x these two
   * factors (picked by the floor's dice when several fit, the nearest one when none does), so a
   * theme works at whatever depth it turns up. `bossByDepth` overrides it.
   */
  bossCrBand: [number, number];
  /** At most this many kinds of ordinary monster per floor; a larger cast is sampled per floor. */
  maxCastSize: number;
  /**
   * The upper edge of a floor's cast: an ordinary monster may cost at most this many times the
   * floor's room budget (budgetByLevel), so a theme's tougher monsters wait for deeper floors.
   */
  castBudgetFactor: number;
  /**
   * The lower edge, on the same scale: an ordinary monster worth less than this share of the
   * floor's room budget is not worth a turn and is left out (waived if nothing else is left).
   */
  castFloorFactor: number;
  /**
   * From this depth on, a theme's lesser bosses (not this floor's boss, challenge rating at most
   * depth x eliteBossCr and below the boss's own) join the regular cast as elites.
   */
  eliteBossFromDepth: number;
  eliteBossCr: number;
  /** Monsters that only appear in ordinary rooms from this depth on (default: always). */
  monsterMinDepth: Record<string, number>;
  /** Monsters that stop appearing in ordinary rooms after this depth (default: never). */
  monsterMaxDepth: Record<string, number>;
  /** Explicit boss monster id for a depth (any monster of the theme); otherwise the theme's boss-role monster. */
  bossByDepth: Partial<Record<number, string>>;
  /**
   * Room budget and boss for a theme at a depth, for every pairing a randomized run can produce
   * (see planRunThemes). Generated by the tuner in src/balance/tune.ts; where a pairing has an
   * entry it replaces budgetByLevel and bossByDepth.
   */
  themeTuning: ThemeTuning;
  /**
   * Re-tune correction: a multiplier on the floor's level budget per depth (index depth-1; 1 when missing). The theme table and
   * the quick party model proved a poor guide for the real engine, so the real-engine measurements of src/balance set this.
   */
  depthScale: number[];
  /** From this depth the boss room's escorts may be of any role and one more than `maxBossMinions` (the boss room is the peak). */
  richEscortsFromDepth: number;
}

