export const SHOVE_PUSH_ID = 'shove_push';
export const SHOVE_TRIP_ID = 'shove_trip';

/**
 * Shove (SRD 5.2.1, Unarmed Strike): the target, no more than one size larger, makes a Strength or Dexterity save
 * (its choice) against 8 + the shover's Strength modifier + Proficiency Bonus or is pushed 5 feet or knocked Prone.
 * Generated by the combat engine for every creature (not stored in `Creature.actions`); the hero sees them in
 * `CombatApi.availableActions()`. For a creature with Extra Attack each shove takes the place of one attack.
 */
export function shovePushAction(): ActionDef {
  return {
    id: SHOVE_PUSH_ID,
    name: 'Shove: Push',
    description: 'Replace one attack: the target (no more than one size larger) makes a Strength or Dexterity save against 8 + your Strength modifier + proficiency or is pushed 5 feet away. A drop or lava behind it hurts.',
    icon: 'shove',
    cost: 'action',
    targeting: { kind: 'creature', melee: true, range: 1 },
    effects: ['shove', 'shove:push'],
  };
}

export function shoveTripAction(): ActionDef {
  return {
    id: SHOVE_TRIP_ID,
    name: 'Shove: Trip',
    description: 'Replace one attack: the target (no more than one size larger) makes a Strength or Dexterity save against 8 + your Strength modifier + proficiency or is knocked Prone.',
    icon: 'shove',
    cost: 'action',
    targeting: { kind: 'creature', melee: true, range: 1 },
    effects: ['shove', 'shove:trip'],
  };
}

export const isShove = (a: ActionDef): boolean => a.effects?.includes('shove') === true;

export function standardActions(): ActionDef[] {
  return [dashAction(), disengageAction(), dodgeAction()];
}
